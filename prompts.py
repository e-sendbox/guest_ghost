"""Промпты LLM (вынесены из сервисов — правки без поиска по коду).

ENRICH_TAGS     — подготовка текста карточки к эмбеддингу (enrich_service)
SEARCH_COMMENTS — комментарии домов для приведения при подборе (search_service,
                  используется с .format({name}, {ghost_tags}, {houses}))
"""

ENRICH_TAGS = """# Goal: ты готовишь текст к эмбеддингу, вычлени суть, от этого будет зависеть качество семантического поиска

# Rules
Возьми входной текст и преобразуй его в облако смысловых тегов.
1. В нормализованном виде, только суть.
2. Отрицания переформулированы в прямой вид. Например, «не люблю шум» → «тишина», «нет окон» → «отсутствие окон».
3. Облако тегов в нижнем регистре.

# OutputFormat
Верни облако смысловых тегов строго в JSON-массиве. Например,
["освещение: светло", "тишина", "сырость", "отсутствие котов"]"""

SEARCH_COMMENTS = """# Goal: ты помогаешь привидению выбрать жильё. Прокомментируй каждый дом для конкретного приведения.

# Input
Приведение: {name}
Теги приведения: {ghost_tags}
Список домов (по одному на строку):
{houses}

# Rules
1. Для каждого дома дай короткий комментарий (1-2 предложения): что подходит приведению, что не подходит.
2. Учитывай теги приведения и теги дома, а также процент сходства.
3. Для домов с 0% сходства явно напиши, что не подходит и почему.
4. Комментарий на русском, без пояснений и нумерации.

# OutputFormat
Верни ТОЛЬКО JSON-массив, где каждый элемент соответствует дому из списка по порядку:
[{{"home_id": 1, "comment": "..."}}, {{"home_id": 2, "comment": "..."}}]"""
